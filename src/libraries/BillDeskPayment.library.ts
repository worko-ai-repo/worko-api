// Import necessary libraries and configurations
import { DateTime } from "luxon";
import jwt from "jsonwebtoken";
import axios from "axios";

// Load constants
import { APP_PAYMENT_BILL_DESK_CONSTANT } from "../configs/constants/Payment.constant";

// Load DTOs
import {
  BillDeskOrderCreateHeaderDTO,
  BillDeskOrderCreatePlainDTO,
  BillDeskOrderCreateResponsePlainDTO,
  BillDeskTransactionResponseEncryptedDTO,
  BillDeskTransactionResponseDecryptedDTO,
} from "../dtos/BillDesk.dto";
import { UserOrderTransactionCreateDTO } from "../dtos/UserOrderTransaction.dto";
import {
  UserOrderProcessGatewayTransactionResponseDTO,
  UserOrderCreateRequestDTO,
  UserOrderCreateResponseDTO,
  UserOrderProcessGatewayTransactionRequestDTO,
} from "../dtos/UserOrder.dto";

// Load enums
import {
  BillDeskOrderCurrencyEnum,
  BillDeskOrderItemCodeEnum,
} from "../enums/BillDesk.enum";

// Load database models
import { DbUserOrderTransactionDto } from "../db/models/UserOrderTransaction.model";
import { DbUserOrderDto } from "../db/models/UserOrder.model";

class BillDeskPaymentLibrary {
  /**
   * Creates an order with BillDesk.
   * @param userEmail - The user's email.
   * @param userOrderRequestBody - The request body for creating the order.
   * @param workoOrderDetails - The details of the worko order.
   * @param workoOrderTransactionDetails - The details of the worko order transaction.
   * @param returnUrl - The URL to return to after creating the order.
   * @returns An object containing the user order response and the BillDesk order create request plain body.
   */
  createOrder = async (
    userEmail: string,
    userOrderRequestBody: UserOrderCreateRequestDTO,
    workoOrderDetails: DbUserOrderDto,
    workoOrderTransactionDetails: DbUserOrderTransactionDto,
    returnUrl: string
  ): Promise<{
    userOrderResponse: UserOrderCreateResponseDTO;
    gatewayOrderRequestPlainBody: BillDeskOrderCreatePlainDTO;
  }> => {
    // BillDesk Order Date in IST
    const orderDateIst = DateTime.now().setZone(
      APP_PAYMENT_BILL_DESK_CONSTANT.TIMESZONE
    );

    // Prepare the BillDesk Create Order Request Body as per the BillDesk documentation
    const bdOrderCreateRequestPlain: BillDeskOrderCreatePlainDTO = {
      mercid: process.env.APP_BILLDESK_MERCHANT_ID as string, // Unique identifier as defined by BillDesk for each merchant
      orderid: workoOrderTransactionDetails.workoPgatewayOrderId, // Unique orderid generated by the merchant to identify the transaction
      amount: workoOrderTransactionDetails.finalAmount.toFixed(2).toString(), // Order amount in two decimals
      order_date: orderDateIst.toFormat(
        APP_PAYMENT_BILL_DESK_CONSTANT.DATETIME_FORMAT
      ), // Merchant order generation date and time in YYYY-MM-DDThh:mm:ssTZD format
      currency: BillDeskOrderCurrencyEnum.INR, // ISO currency of the transaction amount
      ru: returnUrl, // Merchant return url
      additional_info: {
        additional_info1: userEmail, // user email
        additional_info2: workoOrderDetails.userId, // user id
        additional_info3: workoOrderDetails.id, // worko order id
        additional_info4: workoOrderDetails.orderType, // worko order type
        additional_info5: workoOrderTransactionDetails.id, // worko order transaction id
        additional_info6: "NA",
        additional_info7: "NA",
      }, // Array of 7 additional_info values that can be attached to the transaction
      itemcode: BillDeskOrderItemCodeEnum.DIRECT, // Itemcode value as provided by BillDesk, with a default value DIRECT
      device: {
        init_channel: "internet", // Initiating channel, accepted values are internet, app or kiosk
        ip: workoOrderTransactionDetails.userIpAddress, // Customer's IP address of the device or channel from where the transaction is initiated
        user_agent: workoOrderTransactionDetails.userAgent, // Exact content of the HTTP user-agent header
        accept_header: "text/html", // Customer browser accept header values
        // @todo review and update the below details
        // fingerprintid: '61b12c18b5d0cf901be34a23ca64bb19',
        // browser_tz: '-330',
        // browser_color_depth: '32',
        // browser_java_enabled: 'false',
        // browser_screen_height: '1080',
        // browser_screen_width: '1920',
        // browser_language: 'en-US',
        // browser_javascript_enabled: 'true',
      }, // Device object containing information about the customer's device
    };
    global.logger.info(
      "bdOrderCreateRequestPlain: ",
      bdOrderCreateRequestPlain
    );

    // Generate HMAC for the BD Order Details and Prepare the BD Order Create Request
    const billDeskOrderCreateEncryptedBody = this.encryptBillDeskData(
      bdOrderCreateRequestPlain
    );
    global.logger.info(
      "billDeskOrderCreateEncryptedBody: %s",
      billDeskOrderCreateEncryptedBody
    );

    // Prepare the header for the BD Order Create Request as per the BillDesk documentation
    const headers = {
      "Content-Type": "application/jose", // Request Content-Type to take the values application/jose
      Accept: "application/jose", // Accept Response Content-Type to take the values application/jose
      "BD-Traceid": workoOrderTransactionDetails.workoPgatewayOrderId, // Traceid is used for idempotency and the request with the same Traceid within the day will be rejected
      "BD-Timestamp": parseInt(
        orderDateIst.toFormat(APP_PAYMENT_BILL_DESK_CONSTANT.BD_TIMESTAMP)
      ), // Epoch timestamp of the server
    };
    global.logger.info("headers: %s", JSON.stringify(headers));

    // Call the BD API to Create Order
    const bdOrderCreateResponse = axios.post<string>(
      `${process.env.APP_BILLDESK_API_BASE_URL}/orders/create`,
      billDeskOrderCreateEncryptedBody,
      { headers }
    );

    // Decrypt the encrypted bdOrderCreateResponse
    const billDeskOrderCreateDecryptedBody: BillDeskOrderCreateResponsePlainDTO =
      this.billDeskDecryptResponse((await bdOrderCreateResponse).data);
    global.logger.info(
      "billDeskOrderCreateDecryptedBody: ",
      billDeskOrderCreateDecryptedBody
    );

    // Prepare the response with order details
    const orderResponse: UserOrderCreateResponseDTO = {
      pgatewayProvider: workoOrderTransactionDetails.pgatewayProvider,
      userEmail: userEmail,
      orderId: workoOrderDetails.id,
      orderType: workoOrderDetails.orderType,
      orderTxnId: workoOrderTransactionDetails.id,
      workoPgatewayOrderId: workoOrderTransactionDetails.workoPgatewayOrderId,
      pgatewayOrderId: billDeskOrderCreateDecryptedBody.bdorderid, // Unique bdorderid generated by BillDesk for the order
      pgatewayConfig: {
        merchantId: process.env.APP_BILLDESK_MERCHANT_ID,
      },
      pgatewayOrderResponse: billDeskOrderCreateDecryptedBody,
    };

    // Return the response
    return {
      userOrderResponse: orderResponse,
      gatewayOrderRequestPlainBody: bdOrderCreateRequestPlain,
    };
  };

  /**
   * Encrypts the BillDesk order request using JWS-HMAC.
   * @param bdOrder - The BillDesk order request object.
   * @returns The encrypted request as a string.
   */
  encryptBillDeskData(bdOrder: BillDeskOrderCreatePlainDTO): string {
    // Prepare the header for options parameter as per the BillDesk documentation
    const signOptionHeader = {
      clientid: process.env.APP_BILLDESK_CLIENT_ID, // Custom header "clientid" is the clientid value provided by BillDesk
      alg: APP_PAYMENT_BILL_DESK_CONSTANT.ALGORITHM, // The algorithm ("alg" field) with value "HS256"
    };

    // Prepare the sign options for signing the payload/data
    const signOptions: jwt.SignOptions = {
      algorithm: "HS256",
      header: signOptionHeader,
      noTimestamp: true,
    };

    // Sign the order details with the secret key using JWS-HMAC
    return jwt.sign(
      bdOrder,
      process.env.APP_BILLDESK_SECRET_KEY as string,
      signOptions
    );
  }

  /**
   * Decrypts the BillDesk response.
   * @param encryptedString - The encrypted response string.
   * @returns The decrypted response object.
   */
  billDeskDecryptResponse<T>(encryptedString: string): T {
    // Verify and decode the encrypted response using the secret key
    return jwt.verify(
      encryptedString,
      process.env.APP_BILLDESK_SECRET_KEY as string,
      {
        algorithms: ["HS256"],
      }
    ) as T;
  }
  /**
   * Processes the gateway transaction response.
   * @param userEmail - The user's email.
   * @param orderDetails - The details of the order.
   * @param orderTxnDetails - The details of the order transaction.
   * @param workoOrderTransactionDetails - The request DTO for processing the gateway transaction.
   * @returns The processed gateway transaction response DTO.
   */
  processGatewayTransactionResponse = async (
    userEmail: string,
    orderDetails: DbUserOrderDto,
    orderTxnDetails: DbUserOrderTransactionDto,
    workoOrderTransactionDetails: UserOrderProcessGatewayTransactionRequestDTO
  ): Promise<UserOrderProcessGatewayTransactionResponseDTO> => {
    global.logger.info(
      "[BillDeskPaymentLibrary] processGatewayTransactionResponse"
    );

    const { orderId, orderTxnId, pgResponse } = workoOrderTransactionDetails;
    const billDeskResponse =
      pgResponse as BillDeskTransactionResponseEncryptedDTO;

    // Decrypt the encrypted_response
    const decryptedResponse =
      this.billDeskDecryptResponse<BillDeskTransactionResponseDecryptedDTO>(
        billDeskResponse.txnResponse.transaction_response
      );
    global.logger.debug("decryptedResponse", decryptedResponse);

    // Prepare the user order transaction response
    let userOrderTransactionResponse: UserOrderProcessGatewayTransactionResponseDTO =
      {
        userId: orderDetails.userId,
        orderId: orderDetails.id,
        orderType: orderDetails.orderType,
        orderTxnId: orderTxnDetails.id,
        pgatewayProvider: workoOrderTransactionDetails.pgatewayProvider,
        pgResponseDecrypted: decryptedResponse, // Decrypted transaction response from BillDesk
      };
    global.logger.info("userOrderTransactionResponse", userOrderTransactionResponse);
    return userOrderTransactionResponse;
  };
}

// Export defaults
export default new BillDeskPaymentLibrary();
