/**
 * Interface for BillDesk order create plain data.
 * Represents the plain data required for creating a BillDesk order.
 */
export interface BillDeskOrderCreatePlainDTO {
    mercid: string; // Unique identifier as defined by BillDesk for each merchant
    orderid?: string; // Unique order ID generated by the merchant to identify the transaction
    amount: string; // Amount of the transaction (e.g., "300.00")
    order_date: string; // Merchant order generation date and time in "YYYY-MM-DDThh:mm:ssTZD" format (e.g., 2023-07-30T20:25:00+05:30)
    currency: BillDeskOrderCurrencyEnum; // ISO currency of the transaction amount (e.g., "356")
    ru: string; // Merchant return URL (e.g., https://www.example.com/merchant/api/pgresponse)
    itemcode: BillDeskOrderItemCodeEnum; // Item code value as provided by BillDesk, with a default value "DIRECT"
    additional_info?: { [key: string]: string }; // Array of 7 "additional_info" values that can be attached to the transaction
    invoice?: BillDeskOrderCreateInvoicePlainDTO; // Invoice details (optional)
    device: BillDeskOrderCreateDevicePlainDTO; // Device details
}

/**
 * Interface for BillDesk order create response plain data.
 * Represents the plain data returned in the response after creating a BillDesk order.
 */
export interface BillDeskOrderCreateResponsePlainDTO {
    objectid: string; // Object ID (returned as "order")
    orderid: string; // Worko order ID for BillDesk ({orderId}+w+{txnId})
    bdorderid: string; // BillDesk order ID
    mercid: string; // BillDesk merchant ID
    order_date: string; // Worko order date
    amount: string; // Order amount
    currency: string; // Order currency
    ru: string; // Redirect URL
    additional_info: { [key: string]: string }; // Additional info from 1 to 7
    itemcode: string; // Item code
    createdon: string; // Creation date and time
    next_step: string; // Next step
    links: BillDeskOrderCreateResponseLinksDTO[]; // List of objects containing link and OAuth token
    status: BillDeskOrderStatusEnum; // Order status
}

/**
 * Interface for BillDesk transaction create response links object data.
 * Represents the links object data returned in the response after creating a BillDesk transaction.
 */
export interface BillDeskOrderCreateResponseLinksDTO {
    href: string; // URL link
    rel: string; // Relation type
    method: string; // HTTP method
    parameters: {
        mercid: string; // Merchant ID
        bdorderid: string; // BillDesk order ID
        rdata: string; // Additional data
    };
    valid_date: string; // Valid date
    headers: {
        authorization: string; // Authorization header
    };
}

/**
 * Interface for BillDesk transaction response encrypted data.
 * Represents the encrypted data returned in the response of a BillDesk transaction.
 */
export interface BillDeskTransactionResponseEncryptedDTO {
    status: number; // Response status code
    txnResponse: {
        bdcres: string; // BillDesk response code
        failure_reason: string; // Failure reason
        mercid: string; // Merchant ID
        orderid: string; // Order ID
        return_url: string; // Return URL
        status: string; // Transaction status
        terminal_state: string; // Terminal state
        transaction_response: string; // Encrypted transaction response
    };
}

/**
 * Interface for BillDesk transaction response decrypted data.
 * Represents the decrypted data returned in the response of a BillDesk transaction.
 */
export interface BillDeskTransactionResponseDecryptedDTO {
    mercid: string; // Merchant ID
    transaction_date: string; // Transaction date
    surcharge: string; // Surcharge amount
    payment_method_type: string; // Payment method type
    amount: string; // Transaction amount
    ru: string; // Return URL
    orderid: string; // Order ID
    transaction_error_type: BillDeskTransactionErrorTypeEnum; // Transaction error type
    discount: string; // Discount amount
    payment_category: BillDeskPaymentCategoryEnum; // Payment category
    bank_ref_no: string; // Bank reference number
    transactionid: string; // Transaction ID
    txn_process_type: string; // Transaction process type
    bankid: string; // Bank ID
    additional_info: { [key: string]: string }; // Array of 7 "additional_info" values that can be attached to the transaction
    itemcode: BillDeskOrderItemCodeEnum; // Item code
    transaction_error_code: string; // Transaction error code
    currency: BillDeskOrderCurrencyEnum; // Currency
    auth_status: BillDeskTransactionAuthStatusEnum; // Authorization status
    transaction_error_desc: string; // Transaction error description
    objectid: string; // Object ID
    charge_amount: string; // Charge amount
}

