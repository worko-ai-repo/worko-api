export interface BillDeskOrderCreateGstPlainDTO {
    cgst: string; // CGST amount
    sgst: string; // SGST amount
    igst: string; // IGST amount
    gst: string; // GST amount
    cess: string; // Cess amount
    gstincentive: string; // GST incentive
    gstpct: string; // GST percentage
    gstin: string; // GSTIN (Goods and Services Tax Identification Number)
}

